"""Guard the published JSON-LD context against regressions that break consumers.

``context/context.json`` is regenerated by CI from the reasoned import closure.
Two things must hold whatever the closure does:

- the six prefLabel spellings that domain-electrochemistry corrected in 0.38.0
  stay resolvable as context terms (the electrochemistry ``formerLabel``
  property carries them; BattMo writes ``InititalThermodynamicTemperature``);
- no auto-generated ``nsN`` prefix is published (domain-battery #78).
"""

from __future__ import annotations

import json
import re
from pathlib import Path

import pytest

CONTEXT_FILE = Path(__file__).parents[1] / "context" / "context.json"
CTX = json.load(CONTEXT_FILE.open(encoding="utf-8"))["@context"]

ECHEM = "https://w3id.org/emmo/domain/electrochemistry#"
RETIRED_SPELLINGS = {
    "CardonDioxideElectrode": ECHEM + "electrochemistry_573be62a_5aae_4984_9a51_7c50845493df",
    "LithiumNickelMananeseCobaltOxideLithiumManganeseOxideElectrode": ECHEM + "electrochemistry_48e380c3_0441_4761_a80f_3e448cb2f0ba",
    "PostiveElectrodeActivationEnergyOfReaction": ECHEM + "electrochemistry_56b9cd1f_5397_4385_9292_30d93d9e7a05",
    "InititalThermodynamicTemperature": ECHEM + "electrochemistry_9c9b80a4_a00b_4b91_8e17_3a7831f2bf2f",
    "MiniumumTemperature": ECHEM + "electrochemistry_4747c51d_86ab_4684_a4fb_b05f5c405ea3",
    "MiniumumConcentration": ECHEM + "electrochemistry_a9873707_8103_4bb4_9e51_83db1e89b1bd",
}
CURRENT_SPELLINGS = {
    "CarbonDioxideElectrode": RETIRED_SPELLINGS["CardonDioxideElectrode"],
    "PositiveElectrodeActivationEnergyOfReaction": RETIRED_SPELLINGS["PostiveElectrodeActivationEnergyOfReaction"],
    "InitialThermodynamicTemperature": RETIRED_SPELLINGS["InititalThermodynamicTemperature"],
    "MinimumTemperature": RETIRED_SPELLINGS["MiniumumTemperature"],
    "MinimumConcentration": RETIRED_SPELLINGS["MiniumumConcentration"],
}


def _iri(entry) -> str:
    return entry["@id"] if isinstance(entry, dict) else entry


@pytest.mark.parametrize("label, iri", sorted(RETIRED_SPELLINGS.items()))
def test_retired_spelling_still_resolves(label: str, iri: str):
    assert label in CTX, f"retired spelling {label!r} dropped from the context; data using it stops expanding"
    assert _iri(CTX[label]) == iri


@pytest.mark.parametrize("label, iri", sorted(CURRENT_SPELLINGS.items()))
def test_current_spelling_resolves(label: str, iri: str):
    assert label in CTX and _iri(CTX[label]) == iri


def test_no_generated_ns_prefix():
    bad = [k for k, v in CTX.items() if isinstance(v, str) and re.fullmatch(r"ns\d+", k)]
    assert not bad, f"auto-generated prefixes published: {bad}"


def test_units_from_siacceptedunits_present():
    for unit in ("AmpereHour", "MilliAmpereHour", "WattHour", "MolePerLitre", "MilliAmpereHourPerGram"):
        assert unit in CTX, f"{unit} missing: the electrochemistry 0.38.0 siacceptedunits import is not in the closure"
